"""Skill Forge: Generative skill creation with formal specifications and verification."""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum


class StrEnum(str, Enum):
    """Backport of StrEnum for Python < 3.11"""

    pass


from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class SkillTier(StrEnum):
    VERIFIED = "verified"
    COMMUNITY = "community"
    EXPERIMENTAL = "experimental"


class GenerationStage(StrEnum):
    PENDING = "pending"
    SPEC_GENERATED = "spec_generated"
    CODE_GENERATED = "code_generated"
    TESTS_GENERATED = "tests_generated"
    EVAL_RUNNING = "eval_running"
    EVAL_PASSED = "eval_passed"
    EVAL_FAILED = "eval_failed"
    PUBLISHED = "published"
    REJECTED = "rejected"


class FormalSpec(BaseModel):
    """Formal specification for a skill - the contract between user intent and generated code."""

    model_config = ConfigDict(frozen=True)

    id: str
    name: str
    description: str
    version: str
    tier: SkillTier
    triggers: list[TriggerSpec]
    capabilities: list[CapabilitySpec]
    forbidden: list[str]
    blueprints: list[str]
    rule_packs: list[RulePackSpec]
    context: ContextSpec
    budgets: BudgetSpec
    time_value: TimeValueSpec
    evals: EvalSpec
    created_at: datetime
    created_by: str  # user_id
    source_narration: str  # original voice/text description


@dataclass(frozen=True)
class TriggerSpec:
    type: Literal["intent", "event", "schedule"]
    examples: list[str] = field(default_factory=list)
    source: str | None = None
    cron: str | None = None


@dataclass(frozen=True)
class CapabilitySpec:
    name: str
    requires_consent: list[str] = field(default_factory=list)
    description: str = ""
    risk_level: Literal["low", "medium", "high"] = "low"


@dataclass(frozen=True)
class RulePackSpec:
    id: str
    scheme: str
    operator: str | None = None
    citation_url: str = ""
    last_verified: str = ""


@dataclass(frozen=True)
class ContextSpec:
    pin: list[str] = field(default_factory=list)
    retrieve: RetrievalSpec | None = None


@dataclass(frozen=True)
class RetrievalSpec:
    provider: str = "snowflake.cortex_search"
    service: str = "POLICY_SEARCH"
    filter: dict[str, Any] = field(default_factory=dict)
    top_k: int = 4


@dataclass(frozen=True)
class BudgetSpec:
    max_llm_gbp: float = 0.20
    max_call_minutes: int = 30
    max_user_questions: int = 2


@dataclass(frozen=True)
class TimeValueSpec:
    est_user_minutes_saved: int = 15


@dataclass(frozen=True)
class EvalSpec:
    suite: str = "evals/"
    publish_threshold: float = 0.95
    adversarial: bool = True


@dataclass(frozen=True)
class GenerationArtifact:
    """An artifact generated during skill creation."""

    id: str
    skill_id: str
    stage: GenerationStage
    artifact_type: Literal[
        "spec", "manifest", "rule_pack", "mcp_server", "prompts", "tests", "eval_results"
    ]
    content: str | bytes
    file_path: str
    generated_at: datetime
    generator_model: str
    metadata: dict[str, Any] = field(default_factory=dict)


class SkillForgeState(BaseModel):
    """State machine for skill generation pipeline."""

    model_config = ConfigDict(frozen=True)

    skill_id: str
    stage: GenerationStage = GenerationStage.PENDING
    spec: FormalSpec | None = None
    artifacts: list[GenerationArtifact] = field(default_factory=list)
    eval_results: dict[str, Any] | None = None
    error: str | None = None
    updated_at: datetime = Field(default_factory=datetime.utcnow)


